describe('Customer Management Module', () => {
  beforeEach(() => {
    // Basic admin login setup
    cy.login('admin@zobra.test', 'admin123');
    cy.url().should('include', '/dashboard');
    cy.visit('/dashboard/customers');
  });

  it('should display KPI cards with real data', () => {
    cy.get('h1').contains('Customers');
    cy.contains('Total Customers').should('be.visible');
    cy.contains('Active Customers').should('be.visible');
    cy.contains('New This Month').should('be.visible');
    cy.contains('Repeat Customers').should('be.visible');
    cy.contains('Top Customers').should('be.visible');
  });

  it('should search customers', () => {
    // Type in search bar
    cy.get('input[placeholder="Search by name, email, phone, company..."]').type('Rakesh');
    cy.wait(500); // wait for debounce/fetch
    cy.get('table').should('be.visible');
    
    // Check if table rows exist
    cy.get('tbody tr').then($rows => {
      if ($rows.text().includes('No customers found')) {
         cy.log('Database empty, skipping row assertions');
      } else {
         cy.get('tbody tr').first().should('be.visible');
      }
    });
  });

  it('should open the Customer 360 drawer and navigate tabs', () => {
    cy.contains('Loading customers...').should('not.exist');
    cy.get('tbody tr').then($rows => {
      if (!$rows.text().includes('No customers found')) {
         // Click the second column (Name) to ensure we don't click the checkbox
         cy.get('tbody tr').first().find('td').eq(1).click();
         
         // Drawer should open and default to the saved Profile
         cy.contains('Customer ID:', { timeout: 10000 }).should('exist');
         cy.get('[data-cy="customer-profile"]').within(() => {
           ['Name', 'Phone', 'Email', 'Company', 'Pincode', 'Address', 'Address Type', 'City', 'State', 'GST'].forEach((field) => {
             cy.contains(field).should('exist');
           });
         });
         cy.contains('Order Summary').should('exist');

         // Navigate to Orders Tab
         cy.contains('button', 'Orders').click();
         cy.contains('button', 'Orders').should('have.class', 'border-[#111111]');

         // Navigate to Design History Tab
         cy.contains('button', 'Design History').click();
         cy.contains('button', 'Design History').should('have.class', 'border-[#111111]');

         // Navigate to Activity Tab
         cy.contains('button', 'Activity').click();
         cy.contains('button', 'Activity').should('have.class', 'border-[#111111]');

         // No WhatsApp follow-up in the customer details
         cy.get('[data-cy="customer-drawer"]').should('not.contain', 'WhatsApp');

         // Close drawer
         cy.get('button').find('svg.lucide-x').parent().click();
         cy.contains('Customer ID:').should('not.exist');
      }
    });
  });

  it('should save internal notes correctly', () => {
     cy.contains('Loading customers...').should('not.exist');
     cy.get('tbody tr').then($rows => {
      if (!$rows.text().includes('No customers found')) {
         cy.get('tbody tr').first().find('td').eq(1).click();
         cy.contains('Customer ID:', { timeout: 10000 }).should('exist');
         // Notes are stored on the company record, so OTP-only customers have no Notes tab
         cy.get('[data-cy="customer-drawer"]').then(($drawer) => {
           if ($drawer.find('button:contains("Notes")').length === 0) {
             cy.log('Customer has no company record, skipping notes');
             return;
           }
           cy.contains('button', 'Notes').click();

           const testNote = 'Test note generated by Cypress: ' + Date.now();
           cy.get('textarea[placeholder="Write customer notes here..."]').clear().type(testNote);
           cy.contains('button', 'Save Notes').click();
           cy.contains('button', 'Save Notes').should('be.visible');
           cy.get('textarea[placeholder="Write customer notes here..."]').should('have.value', testNote);
         });
      }
     });
  });
});
